"""Canonical vocabulary (ADR-0004): classes attached to every stored value, and the request scope."""

from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import StrEnum
from uuid import UUID

from core.errors import EntitlementDenied, Forbidden


def utcnow() -> datetime:
    return datetime.now(UTC)


class FreshnessClass(StrEnum):
    REAL_TIME = "real_time"
    DELAYED = "delayed"
    END_OF_DAY = "end_of_day"
    HISTORICAL = "historical"
    DEMONSTRATION = "demonstration"


class QualityStatus(StrEnum):
    VALIDATED = "validated"
    ESTIMATED = "estimated"
    SUSPECT = "suspect"
    DEMONSTRATION = "demonstration"


class DataClass(StrEnum):
    """License class of a dataset. Drives the four enforcement points in ADR-0010."""

    PUBLIC = "public"  # free reuse with attribution
    DEMONSTRATION = "demonstration"  # synthetic, generated by AUREX
    LICENSED = "licensed"  # commercial contract, restrictions per license record
    TENANT_PRIVATE = "tenant_private"  # supplied by one tenant, never shared


class InstrumentType(StrEnum):
    EQUITY = "equity"
    ETF = "etf"
    INDEX = "index"
    BOND = "bond"
    FX = "fx"
    COMMODITY = "commodity"
    CRYPTO = "crypto"
    MACRO = "macro"
    RATE = "rate"


class Role(StrEnum):
    OWNER = "owner"
    ADMIN = "admin"
    ANALYST = "analyst"
    VIEWER = "viewer"


ROLE_RANK = {Role.VIEWER: 0, Role.ANALYST: 1, Role.ADMIN: 2, Role.OWNER: 3}


@dataclass(frozen=True)
class Scope:
    """Who is asking and what they may reach. Built by ``security`` and passed to every module call."""

    tenant_id: UUID
    user_id: UUID
    role: Role
    plan: str
    entitlements: frozenset[str] = field(default_factory=frozenset)
    limits: dict[str, int] = field(default_factory=dict)
    platform_admin: bool = False
    via_api_key: bool = False

    def has(self, entitlement: str) -> bool:
        return entitlement in self.entitlements

    def at_least(self, role: Role) -> bool:
        return ROLE_RANK[self.role] >= ROLE_RANK[role]

    def require(self, entitlement: str) -> None:
        if entitlement not in self.entitlements:
            raise EntitlementDenied(
                "The current plan does not include this feature",
                details={"entitlement": entitlement, "plan": self.plan},
            )

    def require_role(self, role: Role) -> None:
        if not self.at_least(role):
            raise Forbidden("Your role does not allow this action", details={"required_role": role.value})

    def check_limit(self, limit: str, current: int) -> None:
        allowed = self.limits.get(limit, 0)
        if current >= allowed:
            raise EntitlementDenied(
                "Plan limit reached", details={"limit": limit, "allowed": allowed, "plan": self.plan}
            )
