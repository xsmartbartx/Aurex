def seed(session: Session) -> None:
    licenses: dict[str, LicenseRecord] = {}
    for spec in LICENSES:
        row = session.scalar(select(LicenseRecord).where(LicenseRecord.code == spec["code"]))
        if row is None:
            row = LicenseRecord(**spec)
            session.add(row)
        else:
            for key in ("attribution", "terms_url", "notes"):
                setattr(row, key, spec.get(key, ""))
        licenses[spec["code"]] = row
    session.flush()
    for spec in DATASETS:
        spec = dict(spec)
        license_code = spec.pop("license")
        row = session.scalar(select(Dataset).where(Dataset.code == spec["code"]))
        if row is None:
            session.add(Dataset(license_id=licenses[license_code].id, **spec))
        else:  # operator changes to enabled, schedule and tracked companies are kept
            row.name, row.description = spec["name"], spec.get("description", "")
            row.config = {**spec.get("config", {}), **row.config}
    session.flush()
