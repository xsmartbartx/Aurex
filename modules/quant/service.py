"""AUREX Quant: point-in-time backtests and Monte Carlo simulations, stored for reproduction.

User code is not executed: strategies are declarative definitions evaluated by the financial engine
(ADR-0009). Every run records its specification, the data cut-off and the engine version.
"""

import hashlib
from datetime import date, datetime, timedelta
from typing import Any
from uuid import UUID

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from core import entitlements as ent
from core.errors import NotFound, ValidationFailure
from core.types import Role, Scope, utcnow
from modules.datalab import access
from modules.logging import record_audit
from modules.processing import ENGINE_VERSION
from modules.processing import backtest as engine
from modules.quant.models import QuantRun

OVERFIT_WARNING = 5


def _family(scope: Scope, symbol: str, strategy: str) -> str:
    return hashlib.sha256(f"{scope.tenant_id}:{symbol}:{strategy}".encode()).hexdigest()[:32]


def _versions(session: Session, scope: Scope, symbol: str, start: date, end: date, known_by: datetime):
    instrument = access.get_instrument(session, scope, symbol)
    series = access.primary_series(session, scope, instrument.id)
    rows = access.series_versions(
        session, scope, series.id, start=start - timedelta(days=800), end=end, known_by=known_by
    )
    _, prov = access.series_meta(session, scope, series.id)
    versions = [engine.Version(ref, known, float(value)) for ref, known, value in rows]
    return instrument, series, prov, versions


def run_backtest(session: Session, scope: Scope, spec: dict[str, Any]) -> dict[str, Any]:
    scope.require(ent.BACKTEST)
    scope.require_role(Role.ANALYST)
    used = session.scalar(
        select(func.count())
        .select_from(QuantRun)
        .where(QuantRun.tenant_id == scope.tenant_id, QuantRun.created_at >= utcnow() - timedelta(days=1))
    )
    scope.check_limit("backtests_per_day", used)
    engine.validate_spec(spec)
    start, end = date.fromisoformat(spec["start"]), date.fromisoformat(spec["end"])
    if end <= start or end > utcnow().date():
        raise ValidationFailure("The period must end after it starts and not in the future")
    data_as_of = utcnow()
    instrument, series, prov, versions = _versions(session, scope, spec["symbol"], start, end, data_as_of)
    result = engine.run(spec, versions, start=start, end=end, initial_capital=float(spec.get("initial_capital", 1e5)))
    family = _family(scope, instrument.symbol, spec["strategy"])
    variants = (
        session.scalar(
            select(func.count())
            .select_from(QuantRun)
            .where(QuantRun.tenant_id == scope.tenant_id, QuantRun.family == family)
        )
        + 1
    )
    result["variants_tried"] = variants
    result["warnings"] = []
    if variants > OVERFIT_WARNING:
        result["warnings"].append(
            f"{variants} variants of this strategy were tested on {instrument.symbol}. Results selected from many "
            "trials overstate what to expect; judge the strategy on its out-of-sample period."
        )
    if prov.license_class == "demonstration":
        result["warnings"].append("The price data is demonstration data generated by AUREX, not market data.")
    result["data"] = {
        "symbol": instrument.symbol,
        "series": series.code,
        "unit": series.unit,
        "dataset": prov.dataset,
        "attribution": prov.attribution,
        "freshness_class": prov.freshness_class,
        "license_class": prov.license_class,
        "versions_used": len(versions),
    }
    row = QuantRun(
        tenant_id=scope.tenant_id,
        user_id=scope.user_id,
        kind="backtest",
        name=spec.get("name") or f"{result['label']} on {instrument.symbol}",
        spec=spec,
        result=result,
        engine_version=ENGINE_VERSION,
        data_as_of=data_as_of,
        family=family,
    )
    session.add(row)
    session.flush()
    record_audit(
        session,
        action="quant.backtest",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="quant_run",
        object_id=row.id,
    )
    return view(row)


def simulate(
    session: Session, scope: Scope, spec: dict[str, Any], *, portfolio: dict[str, Any] | None = None
) -> dict[str, Any]:
    """Monte Carlo from an instrument's or a portfolio's historical daily returns.

    A portfolio's analytics are passed in by the caller (the API composes the two modules).
    """
    scope.require(ent.SIMULATE)
    scope.require_role(Role.ANALYST)
    lookback = int(spec.get("lookback_days", 756))
    seed = int(spec.get("seed") or int(utcnow().timestamp()) % 1_000_000)
    data_as_of = utcnow()
    if spec.get("portfolio_id"):
        analytics = portfolio or {"empty": True}
        if analytics.get("empty"):
            raise ValidationFailure("The portfolio has no history to simulate from")
        index = [p["index"] for p in analytics["history"]][-lookback:]
        returns = [index[i] / index[i - 1] - 1 for i in range(1, len(index))]
        subject, start_value = analytics["portfolio"]["name"], analytics["value"]
        data = {"portfolio": subject, "base_currency": analytics["base_currency"]}
    else:
        instrument, series, prov, versions = _versions(
            session,
            scope,
            spec["symbol"],
            data_as_of.date() - timedelta(days=int(lookback * 1.5)),
            data_as_of.date(),
            data_as_of,
        )
        latest: dict[date, float] = {}
        for version in sorted(versions, key=lambda v: v.known_at):
            latest[version.ref] = version.value
        values = [latest[d] for d in sorted(latest)][-lookback:]
        returns = [values[i] / values[i - 1] - 1 for i in range(1, len(values)) if values[i - 1]]
        subject, start_value = instrument.symbol, values[-1] if values else 100.0
        data = {
            "symbol": instrument.symbol,
            "dataset": prov.dataset,
            "license_class": prov.license_class,
            "attribution": prov.attribution,
        }
    result = engine.monte_carlo(
        returns,
        horizon=int(spec.get("horizon", 252)),
        paths=int(spec.get("paths", 2000)),
        method=spec.get("method", "bootstrap"),
        seed=seed,
        start_value=start_value,
    )
    result["data"] = data
    stored = {**spec, "seed": seed}
    row = QuantRun(
        tenant_id=scope.tenant_id,
        user_id=scope.user_id,
        kind="monte_carlo",
        name=f"Monte Carlo · {subject}",
        spec=stored,
        result=result,
        engine_version=ENGINE_VERSION,
        data_as_of=data_as_of,
        family="",
    )
    session.add(row)
    session.flush()
    record_audit(
        session,
        action="quant.simulation",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="quant_run",
        object_id=row.id,
    )
    return view(row)


def view(row: QuantRun, *, full: bool = True) -> dict[str, Any]:
    out = {
        "id": row.id,
        "kind": row.kind,
        "name": row.name,
        "spec": row.spec,
        "engine_version": row.engine_version,
        "data_as_of": row.data_as_of,
        "created_at": row.created_at,
    }
    if full:
        out["result"] = row.result
    else:
        metrics = row.result.get("metrics") or row.result.get("terminal") or {}
        out["summary"] = {
            k: metrics.get(k) for k in ("total_return", "sharpe", "max_drawdown", "p50", "probability_of_loss")
        }
    return out


def _own(session: Session, scope: Scope, run_id: UUID) -> QuantRun:
    row = session.get(QuantRun, run_id)
    if row is None or row.tenant_id != scope.tenant_id or row.user_id != scope.user_id:
        raise NotFound("Run not found")
    return row


def list_runs(session: Session, scope: Scope, *, limit: int = 50) -> list[dict[str, Any]]:
    rows = session.scalars(
        select(QuantRun)
        .where(QuantRun.tenant_id == scope.tenant_id, QuantRun.user_id == scope.user_id)
        .order_by(QuantRun.created_at.desc())
        .limit(limit)
    )
    return [view(r, full=False) for r in rows]


def get_run(session: Session, scope: Scope, run_id: UUID) -> dict[str, Any]:
    return view(_own(session, scope, run_id))


def delete_run(session: Session, scope: Scope, run_id: UUID) -> None:
    session.delete(_own(session, scope, run_id))


def reproduce(session: Session, scope: Scope, run_id: UUID) -> dict[str, Any]:
    """Re-run from the recorded inputs: the same specification on data as it was known at the run."""
    row = _own(session, scope, run_id)
    spec = row.spec
    if row.kind == "backtest":
        start, end = date.fromisoformat(spec["start"]), date.fromisoformat(spec["end"])
        _, _, _, versions = _versions(session, scope, spec["symbol"], start, end, row.data_as_of)
        again = engine.run(
            spec, versions, start=start, end=end, initial_capital=float(spec.get("initial_capital", 1e5))
        )
        keys = ("total_return", "cagr", "volatility", "sharpe", "max_drawdown")
        before, after = row.result["metrics"], again["metrics"]
    else:
        return {
            "reproducible": True,
            "detail": "Simulations are seeded; the stored seed reproduces the paths.",
            "seed": spec.get("seed"),
        }
    same = all(
        (before.get(k) is None and after.get(k) is None)
        or (before.get(k) is not None and after.get(k) is not None and abs(before[k] - after[k]) < 1e-12)
        for k in keys
    )
    return {
        "identical": same,
        "recorded": {k: before.get(k) for k in keys},
        "reproduced": {k: after.get(k) for k in keys},
        "data_as_of": row.data_as_of,
        "engine_version": ENGINE_VERSION,
        "recorded_engine_version": row.engine_version,
    }
