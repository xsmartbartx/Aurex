Screen = Callable[[str], bool]
STALE_AFTER = timedelta(minutes=15)
DISCLAIMER = (
    "Generated by AUREX from the evidence listed. Analysis and simulation only; not investment advice "
    "and not a recommendation to buy or sell."
)
_engine_override: Engine | None = None


def set_engine(engine: Engine | None) -> None:
    """Replace the engine (evaluation harness and tests)."""
    global _engine_override
    _engine_override = engine


def select_engine(allow_external: bool) -> Engine:
    """An external model is used only when one is configured and the tenant's policy allows it."""
    if _engine_override is not None:
        return _engine_override
    adapter = default_model() if allow_external else None
    return ModelEngine(adapter) if adapter is not None else OfflineEngine()


# --- Questions and answer records -----------------------------------------------------------------


def open_question(
    session: Session,
    scope: Scope,
    *,
    question: str,
    agent: str = "research",
    context: dict[str, Any] | None = None,
    kind: str = "answer",
) -> AnswerRecord:
    """Create the record for a question. The run itself follows in ``answer_question``."""
    scope.require(ent.ASK)
    scope.require_role(Role.ANALYST)
    if kind == "report":
        scope.require(ent.REPORTS)
    if agent not in AGENTS:
        raise ValidationFailure("Unknown agent", details={"allowed": sorted(AGENTS)})
    question = clean_text(question, max_len=2000)
    if len(question) < 3:
        raise ValidationFailure("Ask a question of at least three characters")
    record = AnswerRecord(
        tenant_id=scope.tenant_id,
        user_id=scope.user_id,
        kind=kind,
        agent=agent,
        question=question,
        title=question[:200],
        scope={"context": _clean_context(context)},
        status="running",
    )
    session.add(record)
    session.flush()
    record_audit(
        session,
        action="intelligence.question",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="answer_record",
        object_id=record.id,
        agent=agent,
    )
    return record


def _clean_context(context: dict[str, Any] | None) -> dict[str, Any]:
    allowed = ("symbol", "portfolio", "thesis", "node")
    return {k: str(v)[:120] for k, v in (context or {}).items() if k in allowed and v}


def answer_question(
    session: Session, scope: Scope, record_id: UUID, *, screen: Screen | None = None, allow_external: bool = True
) -> AnswerRecord:
    """Run the agent for a stored question and write the verified answer into its record."""
    record = _own_record(session, scope, record_id)
    engine = select_engine(allow_external)
    tools = Toolbox(session, scope, external=engine.external).build()
    settings = get_settings()
    question = record.question
    if record.kind == "report":
        question += (
            "\n\nWrite this as a research report: business and recent results, growth and margins, "
            "cash generation, debt and sensitivity to interest rates, what the filings say about risk, "
            "and which data is current and which is missing."
        )
    try:
        answer = run(
            agent=AGENTS[record.agent],
            question=question,
            context=record.scope.get("context", {}),
            tools=tools,
            entitlements=scope.entitlements,
            engine=engine,
            screen=screen,
            limits=Limits(max_steps=settings.ai_max_steps, max_seconds=settings.ai_max_seconds),
        )
    except AurexError as exc:
        record.status = "failed"
        record.answer = {"error": {"code": exc.code, "message": exc.message}}
        record_audit(
            session,
            action="intelligence.answer",
            tenant_id=scope.tenant_id,
            actor_id=scope.user_id,
            object_type="answer_record",
            object_id=record.id,
            outcome="failure",
            code=exc.code,
        )
        return record
    record.status = "complete"
    record.title = answer.title or record.title
    record.engine, record.model_id = answer.engine, answer.model_id
    record.answer = answer.to_dict() | {"disclaimer": DISCLAIMER}
    record.usage = answer.usage
    record.data_versions = _data_versions(session, scope, answer.to_dict()["evidence"])
    # Agent tool calls are part of the audit trail.
    for call in answer.calls:
        record_audit(
            session,
            action="agent.tool_call",
            tenant_id=scope.tenant_id,
            actor_id=scope.user_id,
            object_type="answer_record",
            object_id=record.id,
            outcome="success" if call.outcome == "ok" else call.outcome,
            tool=call.tool,
            agent=record.agent,
        )
    channel = "model_external" if answer.external else "model_local"
    for info in record.data_versions.get("datasets", {}).values():
        access.count_usage(session, scope, UUID(info["id"]), channel)  # reported to licensors per dataset
    return record


def _data_versions(session: Session, scope: Scope, evidence: list[dict[str, Any]]) -> dict[str, Any]:
    """What the answer was computed from: datasets with their state, and the moment of the read."""
    codes = sorted({e.get("source", {}).get("dataset") for e in evidence} - {None})
    datasets = {}
    for dataset in access.list_datasets(session, scope):
        if dataset.code in codes:
            datasets[dataset.code] = {
                "id": str(dataset.id),
                "status": dataset.status,
                "freshness_class": dataset.freshness_class,
                "last_success_at": dataset.last_success_at.isoformat() if dataset.last_success_at else None,
                "latest_ref_time": dataset.latest_ref_time.isoformat() if dataset.latest_ref_time else None,
                "license_class": dataset.license.data_class,
                "attribution": dataset.license.attribution,
            }
    return {"as_of": utcnow().isoformat(), "engine_version": ENGINE_VERSION, "datasets": datasets}


def _own_record(session: Session, scope: Scope, record_id: UUID, *, shared_ok: bool = False) -> AnswerRecord:
    record = session.get(AnswerRecord, record_id)
    if (
        record is None
        or record.tenant_id != scope.tenant_id
        or (record.user_id != scope.user_id and not (shared_ok and record.shared))
    ):
        raise NotFound("Answer not found")
    return record


def record_view(record: AnswerRecord, scope: Scope) -> dict[str, Any]:
    status = record.status
    if status == "running" and utcnow() - record.created_at > STALE_AFTER:
        status = "failed"
    return {
        "id": record.id,
        "kind": record.kind,
        "agent": record.agent,
        "agent_title": AGENTS[record.agent].title,
        "title": record.title,
        "question": record.question,
        "status": status,
        "engine": record.engine,
        "model_id": record.model_id,
        "created_at": record.created_at,
        "shared": record.shared,
        "own": record.user_id == scope.user_id,
        "answer": record.answer,
        "usage": record.usage,
        "data_versions": record.data_versions,
        "context": record.scope.get("context", {}),
    }


def get_record(session: Session, scope: Scope, record_id: UUID) -> dict[str, Any]:
    return record_view(_own_record(session, scope, record_id, shared_ok=True), scope)


def list_records(session: Session, scope: Scope, *, limit: int = 40) -> list[dict[str, Any]]:
    rows = session.scalars(
        select(AnswerRecord)
        .where(
            AnswerRecord.tenant_id == scope.tenant_id,
            or_(AnswerRecord.user_id == scope.user_id, AnswerRecord.shared.is_(True)),
        )
        .order_by(AnswerRecord.created_at.desc())
        .limit(limit)
    )
    return [
        {
            "id": r.id,
            "kind": r.kind,
            "agent": r.agent,
            "title": r.title,
            "status": r.status,
            "engine": r.engine,
            "created_at": r.created_at,
            "shared": r.shared,
            "own": r.user_id == scope.user_id,
            "supported": (r.answer.get("counts") or {}).get("supported", 0),
        }
        for r in rows
    ]


def share_record(session: Session, scope: Scope, record_id: UUID, shared: bool) -> None:
    """Sharing inside the team is a side effect, so it happens only on the user's explicit request."""
    record = _own_record(session, scope, record_id)
    record.shared = shared
    record_audit(
        session,
        action="intelligence.answer_shared" if shared else "intelligence.answer_unshared",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="answer_record",
        object_id=record.id,
    )


def delete_record(session: Session, scope: Scope, record_id: UUID) -> None:
    session.delete(_own_record(session, scope, record_id))
    record_audit(
        session,
        action="intelligence.answer_deleted",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="answer_record",
        object_id=record_id,
    )


def reproduce(session: Session, scope: Scope, record_id: UUID) -> dict[str, Any]:
    """Re-run every calculation of a record against the data as it was known when the answer was written."""
    record = _own_record(session, scope, record_id, shared_ok=True)
    if record.status != "complete":
        raise ValidationFailure("Only a complete answer can be reproduced")
    as_of = datetime.fromisoformat(record.data_versions["as_of"])
    external = bool((record.answer.get("generated_by") or {}).get("external_provider"))
    tools = Toolbox(session, scope, external=external, as_of=as_of).build()
    context = RunContext(
        agent=AGENTS["research"],
        question="",
        context={},
        tools=tools,
        entitlements=scope.entitlements,
        limits=Limits(max_tool_calls=200),
        screen=None,
    )
    recorded = [e for e in record.answer.get("evidence", []) if e.get("kind") == "calculation" and e.get("recipe")]
    done = set()
    for item in recorded:
        recipe = item["recipe"]
        key = (recipe["tool"], repr(sorted(recipe["input"].items())))
        if key not in done:
            done.add(key)
            context.call(recipe["tool"], dict(recipe["input"]))
    fresh = {e.label: e.value for e in context.ledger.all()}
    results = []
    for item in recorded:
        value, before = fresh.get(item["label"]), item.get("value")
        same = value is not None and before is not None and abs(value - before) <= 1e-9 * max(1.0, abs(before))
        results.append(
            {"id": item["id"], "label": item["label"], "recorded": before, "reproduced": value, "identical": same}
        )
    return {
        "record_id": record.id,
        "as_of": as_of,
        "engine_version": ENGINE_VERSION,
        "recorded_engine_version": record.data_versions.get("engine_version"),
        "calculations": results,
        "identical": all(r["identical"] for r in results),
        "checked": len(results),
    }


# --- Documents ------------------------------------------------------------------------------------


def search(
    session: Session,
    scope: Scope,
    query: str,
    *,
    entity_id: UUID | None = None,
    doc_types: list[str] | None = None,
    limit: int = 20,
) -> list[Any]:
    scope.require(ent.DOCUMENTS)
    return access.search_passages(
        session,
        scope,
        clean_text(query, max_len=300),
        entity_ids=[entity_id] if entity_id else [],
        doc_types=doc_types or [],
        limit=limit,
    )


def upload_document(session: Session, scope: Scope, *, title: str, body: str, screen: Screen | None = None) -> UUID:
    """Store a tenant-private text document. The content is untrusted: it is screened passage by passage."""
    scope.require(ent.DOCUMENTS)
    scope.require_role(Role.ANALYST)
    title = clean_text(title, max_len=200)
    if not title or len(body.strip()) < 20:
        raise ValidationFailure("A document needs a title and some text")
    if len(body) > get_settings().max_upload_bytes:
        raise ValidationFailure("The document is too large", details={"max_bytes": get_settings().max_upload_bytes})
    if "\x00" in body:
        raise ValidationFailure("The document is not plain text")
    digest = hashlib.sha256(body.encode()).hexdigest()
    passages = [(location, text, bool(screen and screen(text))) for location, text in split_passages(body)]
    document_id = access.store_private_document(
        session,
        scope,
        key=f"upload:{digest[:32]}",
        title=title,
        content_hash=digest,
        passages=passages,
        meta={"uploaded_by": str(scope.user_id)},
    )
    flagged = sum(1 for _, _, bad in passages if bad)
    record_audit(
        session,
        action="intelligence.document_uploaded",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="document",
        object_id=document_id,
        passages=len(passages),
        flagged=flagged,
    )
    return document_id


def delete_document(session: Session, scope: Scope, document_id: UUID) -> None:
    scope.require_role(Role.ANALYST)
    access.delete_private_document(session, scope, document_id)
    record_audit(
        session,
        action="intelligence.document_deleted",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="document",
        object_id=document_id,
    )


# --- Fundamentals ---------------------------------------------------------------------------------


def company_fundamentals(session: Session, scope: Scope, entity_id: UUID, *, years: int = 5) -> dict[str, Any]:
    """Statements and ratios per fiscal year, each figure with the fact it came from."""
    entity = access.get_entity(session, scope, entity_id)
    facts, prov = access.entity_facts(session, scope, entity_id)
    analysis = fnd.analyze([f.model_dump() for f in facts], max_years=years)
    out = []
    for year in analysis["years"]:
        out.append(
            {
                "fiscal_year": year["fiscal_year"],
                "period_end": year["period_end"],
                "items": {
                    name: {
                        "value": float(item["value"]),
                        "unit": item["unit"],
                        "label": item["label"],
                        "concept": item["concept"],
                        "accession": item["accession"],
                        "filed_at": item["filed_at"],
                        "fact_id": item["fact_id"],
                    }
                    for name, item in year["items"].items()
                },
                "ratios": {
                    name: {
                        "value": ratio.output,
                        "unit": ratio.unit,
                        "label": RATIO_LABEL.get(name, name),
                        "definition": ratio.definition,
                        "inputs": ratio.inputs,
                    }
                    for name, ratio in year["ratios"].items()
                },
            }
        )
    return {
        "entity": entity,
        "years": out,
        "missing": analysis["missing"],
        "provenance": prov,
        "engine_version": ENGINE_VERSION,
    }


# --- Theses ---------------------------------------------------------------------------------------

OPERATORS = ("above", "below")


def _thesis_view(session: Session, scope: Scope, thesis: Thesis) -> dict[str, Any]:
    conditions = []
    for condition in thesis.conditions:
        try:
            series, prov = access.series_meta(session, scope, UUID(condition["series_id"]))
            value = series.latest_value
            conditions.append(
                {
                    **condition,
                    "series": series.name,
                    "unit": series.unit,
                    "latest": value,
                    "latest_at": series.latest_ref_time,
                    "freshness_class": prov.freshness_class,
                    "holds": _holds(condition, value),
                }
            )
        except AurexError:
            conditions.append({**condition, "series": "unavailable", "holds": None})
    return {
        "id": thesis.id,
        "title": thesis.title,
        "statement": thesis.statement,
        "status": thesis.status,
        "conditions": conditions,
        "history": thesis.history[-20:],
        "last_checked_at": thesis.last_checked_at,
        "created_at": thesis.created_at,
    }


def _holds(condition: dict[str, Any], value: float | Decimal | None) -> bool | None:
    if value is None:
        return None
    threshold = float(condition["value"])
    return float(value) > threshold if condition["operator"] == "above" else float(value) < threshold


def list_theses(session: Session, scope: Scope) -> list[dict[str, Any]]:
    scope.require(ent.THESES)
    rows = session.scalars(
        select(Thesis)
        .where(Thesis.tenant_id == scope.tenant_id, Thesis.user_id == scope.user_id)
        .order_by(Thesis.created_at.desc())
    )
    return [_thesis_view(session, scope, t) for t in rows]


def save_thesis(
    session: Session,
    scope: Scope,
    *,
    thesis_id: UUID | None,
    title: str,
    statement: str,
    conditions: list[dict[str, Any]],
) -> dict[str, Any]:
    """A thesis holds while each condition is true, e.g. "ECB deposit rate stays below 3"."""
    scope.require(ent.THESES)
    scope.require_role(Role.ANALYST)
    if not 1 <= len(conditions) <= 8:
        raise ValidationFailure("A thesis has between 1 and 8 monitored conditions")
    clean = []
    for condition in conditions:
        if condition.get("operator") not in OPERATORS:
            raise ValidationFailure("A condition is 'above' or 'below' a value", details={"allowed": list(OPERATORS)})
        instrument = access.get_instrument(session, scope, str(condition.get("instrument", "")))
        series = access.primary_series(session, scope, instrument.id)
        clean.append(
            {
                "series_id": str(series.id),
                "instrument": instrument.symbol,
                "operator": condition["operator"],
                "value": float(condition["value"]),
                "description": clean_text(str(condition.get("description", "")), max_len=200),
            }
        )
    if thesis_id:
        thesis = session.get(Thesis, thesis_id)
        if thesis is None or thesis.tenant_id != scope.tenant_id or thesis.user_id != scope.user_id:
            raise NotFound("Thesis not found")
    else:
        thesis = Thesis(tenant_id=scope.tenant_id, user_id=scope.user_id, history=[])
        session.add(thesis)
    thesis.title, thesis.statement, thesis.conditions = clean_text(title, max_len=160), statement[:4000], clean
    session.flush()
    record_audit(
        session,
        action="thesis.saved",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="thesis",
        object_id=thesis.id,
    )
    check_theses(session, thesis_ids=[thesis.id])
    return _thesis_view(session, scope, thesis)


def delete_thesis(session: Session, scope: Scope, thesis_id: UUID) -> None:
    thesis = session.get(Thesis, thesis_id)
    if thesis is None or thesis.tenant_id != scope.tenant_id or thesis.user_id != scope.user_id:
        raise NotFound("Thesis not found")
    session.delete(thesis)
    record_audit(
        session,
        action="thesis.deleted",
        tenant_id=scope.tenant_id,
        actor_id=scope.user_id,
        object_type="thesis",
        object_id=thesis_id,
    )


def check_theses(
    session: Session,
    *,
    series_ids: list[UUID] | None = None,
    thesis_ids: list[UUID] | None = None,
    notify: Callable[..., None] | None = None,
) -> int:
    """Thesis Monitor: after new data arrives, mark a thesis whose condition no longer holds.

    Runs across tenants in a system session, or for given theses in a tenant session. Changing a thesis
    stays with its owner; the monitor only records the signal and notifies.
    """
    stmt = select(Thesis).where(Thesis.status != "closed")
    if thesis_ids:
        stmt = stmt.where(Thesis.id.in_(thesis_ids))
    changed = 0
    wanted = {str(s) for s in series_ids} if series_ids else None
    for thesis in session.scalars(stmt):
        ids = [c["series_id"] for c in thesis.conditions]
        if wanted is not None and not wanted & set(ids):
            continue
        latest = access.latest_values(session, [UUID(i) for i in ids])
        broken = [c for c in thesis.conditions if _holds(c, latest.get(UUID(c["series_id"]))) is False]
        status = "challenged" if broken else "holding"
        thesis.last_checked_at = utcnow()
        if status != thesis.status:
            thesis.status = status
            detail = "; ".join(f"{c['instrument']} is no longer {c['operator']} {c['value']:g}" for c in broken)
            thesis.history = [*thesis.history, {"at": utcnow().isoformat(), "status": status, "detail": detail}]
            changed += 1
            if notify and status == "challenged":
                notify(
                    session,
                    tenant_id=thesis.tenant_id,
                    user_id=thesis.user_id,
                    kind="thesis",
                    title=f"Thesis challenged: {thesis.title}",
                    body=detail,
                    link="/app/intelligence?tab=theses",
                )
    return changed
