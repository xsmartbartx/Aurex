"use client";

import { AlertTriangle } from "lucide-react";
import { FRESHNESS_LABEL, fmtAge, fmtDate } from "@/lib/format";
import type { Provenance } from "@/lib/types";
import { Badge } from "./ui";

const FRESHNESS_TONE = {
  real_time: "up", delayed: "info", end_of_day: "info", historical: "neutral", demonstration: "demo",
} as const;

/** Freshness class next to a value. Demonstration data is always marked. */
export function FreshnessBadge({ freshness, delay }: { freshness: string; delay?: number }) {
  const label = FRESHNESS_LABEL[freshness] ?? freshness;
  return (
    <Badge
      tone={FRESHNESS_TONE[freshness as keyof typeof FRESHNESS_TONE] ?? "neutral"}
      title={freshness === "demonstration" ? "Generated by AUREX. Not market data." : `Data freshness: ${label}`}
    >
      {label}
      {freshness === "delayed" && delay ? ` ${delay}m` : ""}
    </Badge>
  );
}

export function StatusBadge({ status }: { status: string }) {
  if (status === "ok") return null;
  const text: Record<string, string> = {
    stale: "Stale", failed: "Import failed", never_run: "Not loaded", not_configured: "Not configured",
  };
  return (
    <Badge tone={status === "failed" ? "down" : "gold"} title="Dataset status. See DataLab for details.">
      <AlertTriangle size={10} className="mr-1" />
      {text[status] ?? status}
    </Badge>
  );
}

/** Source, age and license of what is on screen. The attribution text is the provider's required wording. */
export function ProvenanceLine({ provenance, asOf }: { provenance: Provenance; asOf?: string | null }) {
  return (
    <div className="flex flex-wrap items-center gap-x-3 gap-y-1 text-[11px] text-faint">
      <FreshnessBadge freshness={provenance.freshness_class} delay={provenance.delay_minutes} />
      <StatusBadge status={provenance.status} />
      <span title={provenance.attribution} className="truncate">
        {provenance.attribution}
      </span>
      <span className="num whitespace-nowrap">
        {asOf ? `as known ${fmtDate(asOf)}` : `latest ${fmtDate(provenance.latest_ref_time)}`} · imported{" "}
        {fmtAge(provenance.last_success_at)}
      </span>
      <span className="whitespace-nowrap">license: {provenance.license_class.replaceAll("_", " ")}</span>
    </div>
  );
}
